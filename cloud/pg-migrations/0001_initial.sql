CREATE FUNCTION member_sync_insert_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 UPDATE settings SET value=((value::bigint)+1)::text WHERE id='sync-version';
 INSERT INTO audit(id,actor_id,action,target_id,created_at) VALUES (md5(random()::text || clock_timestamp()::text),NEW.owner_id,'member.create',NEW.id,NEW.created_at);
 RETURN NEW;
END $$;
CREATE TRIGGER member_sync_insert AFTER INSERT ON members FOR EACH ROW EXECUTE FUNCTION member_sync_insert_fn();
CREATE FUNCTION sync_version_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN UPDATE settings SET value=((value::bigint)+1)::text WHERE id='sync-version'; RETURN NEW; END $$;
CREATE TRIGGER member_sync_update AFTER UPDATE ON members FOR EACH ROW EXECUTE FUNCTION sync_version_fn();
CREATE TRIGGER user_sync_insert AFTER INSERT ON users FOR EACH ROW EXECUTE FUNCTION sync_version_fn();
CREATE TRIGGER user_sync_update AFTER UPDATE ON users FOR EACH ROW EXECUTE FUNCTION sync_version_fn();
CREATE TRIGGER service_sync_insert AFTER INSERT ON service_records FOR EACH ROW EXECUTE FUNCTION sync_version_fn();
CREATE TRIGGER service_sync_update AFTER UPDATE ON service_records FOR EACH ROW EXECUTE FUNCTION sync_version_fn();
CREATE FUNCTION operation_audit_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO audit(id,actor_id,action,target_id,created_at) VALUES (NEW.id,NEW.actor_id,CASE WHEN (NEW.result::jsonb ->> 'deleted')::boolean IS TRUE THEN 'member.delete' ELSE 'member.save' END,NEW.member_id,NEW.created_at);
 RETURN NEW;
END $$;
CREATE TRIGGER operation_audit AFTER INSERT ON operations FOR EACH ROW EXECUTE FUNCTION operation_audit_fn();
CREATE FUNCTION active_member_guard_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM members WHERE id=NEW.member_id AND archived=0) THEN RAISE EXCEPTION 'member_unavailable'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER media_active_insert BEFORE INSERT OR UPDATE ON media FOR EACH ROW EXECUTE FUNCTION active_member_guard_fn();
CREATE TRIGGER original_active_insert BEFORE INSERT OR UPDATE ON photo_sources FOR EACH ROW EXECUTE FUNCTION active_member_guard_fn();
CREATE FUNCTION service_active_guard_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM members WHERE id=NEW.owner_member_id AND archived=0) THEN RAISE EXCEPTION 'member_unavailable'; END IF;
 IF TG_OP='INSERT' THEN
  IF NOT EXISTS(SELECT 1 FROM members WHERE id=NEW.counterpart_member_id AND archived=0 AND confirmed_id IS NOT NULL) THEN RAISE EXCEPTION 'member_unavailable'; END IF;
 ELSIF NEW.counterpart_member_id<>OLD.counterpart_member_id THEN
  IF NOT EXISTS(SELECT 1 FROM members WHERE id=NEW.counterpart_member_id AND archived=0 AND confirmed_id IS NOT NULL) THEN RAISE EXCEPTION 'member_unavailable'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER service_active_guard BEFORE INSERT OR UPDATE ON service_records FOR EACH ROW EXECUTE FUNCTION service_active_guard_fn();
