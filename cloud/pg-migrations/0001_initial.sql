CREATE TABLE users (id text PRIMARY KEY, username text NOT NULL UNIQUE, display_name text NOT NULL, password_hash text, role text NOT NULL CHECK (role IN ('admin','teacher')), active integer NOT NULL DEFAULT 1, created_at bigint NOT NULL);
CREATE TABLE settings (id text PRIMARY KEY, value text NOT NULL);
CREATE TABLE sessions (hash text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id), expires_at bigint NOT NULL);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE TABLE invitations (hash text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id), expires_at bigint NOT NULL, used_at bigint, claim text);
CREATE TABLE limits (key text PRIMARY KEY, count integer NOT NULL, expires_at bigint NOT NULL);
CREATE TABLE members (
 seq integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (seq BETWEEN 1 AND 999999),
 id text NOT NULL UNIQUE, owner_id text NOT NULL REFERENCES users(id), request_key text NOT NULL,
 gender text NOT NULL CHECK (gender IN ('男','女')), name text NOT NULL DEFAULT '', birth text NOT NULL DEFAULT '',
 profile text NOT NULL DEFAULT '{}', editor text NOT NULL DEFAULT '{}', photo_id text,
 version integer NOT NULL DEFAULT 0, confirmed_id text, status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending','confirmed')),
 archived integer NOT NULL DEFAULT 0, last_operation text, created_at bigint NOT NULL, updated_at bigint NOT NULL,
 deleted_at bigint, deleted_by text REFERENCES users(id), UNIQUE(owner_id,request_key)
);
CREATE INDEX members_recent ON members(archived,updated_at DESC,seq DESC);
CREATE INDEX members_filter ON members(gender,status,owner_id);
CREATE INDEX members_admin_list ON members(archived,updated_at DESC,seq DESC);
ALTER SEQUENCE members_seq_seq MAXVALUE 999999 NO CYCLE;
CREATE TABLE media (id text PRIMARY KEY, member_id text NOT NULL REFERENCES members(id), kind text NOT NULL CHECK (kind IN ('photo','card','thumb')), object_key text NOT NULL UNIQUE, digest text NOT NULL, content_type text NOT NULL, size bigint NOT NULL, width integer NOT NULL, height integer NOT NULL, state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','ready','deleting')), created_at bigint NOT NULL);
CREATE INDEX media_member ON media(member_id);
CREATE TABLE snapshots (id text PRIMARY KEY, member_id text NOT NULL REFERENCES members(id), profile text NOT NULL, editor text NOT NULL, photo_id text NOT NULL REFERENCES media(id), card_id text NOT NULL REFERENCES media(id), thumb_id text NOT NULL REFERENCES media(id), created_at bigint NOT NULL);
CREATE INDEX snapshots_member ON snapshots(member_id);
CREATE TABLE operations (id text PRIMARY KEY, member_id text NOT NULL REFERENCES members(id), actor_id text NOT NULL REFERENCES users(id), digest text NOT NULL, result text NOT NULL, created_at bigint NOT NULL);
CREATE TABLE audit (id text PRIMARY KEY, actor_id text NOT NULL, action text NOT NULL, target_id text NOT NULL, created_at bigint NOT NULL);
CREATE TABLE access_sessions (hash text PRIMARY KEY, access_version text NOT NULL, expires_at bigint NOT NULL);
CREATE INDEX access_sessions_expiry ON access_sessions(expires_at);
CREATE TABLE service_records (
 id text PRIMARY KEY, owner_member_id text NOT NULL REFERENCES members(id), counterpart_member_id text NOT NULL REFERENCES members(id),
 counterpart_name_snapshot text NOT NULL, counterpart_number_snapshot text NOT NULL, appointment_at bigint NOT NULL,
 status text NOT NULL CHECK (status IN ('pending','completed','cancelled','no_show')), note text NOT NULL DEFAULT '' CHECK (length(note)<=300),
 created_by text NOT NULL REFERENCES users(id), recorder_name_snapshot text NOT NULL, updated_by text NOT NULL REFERENCES users(id),
 created_at bigint NOT NULL, updated_at bigint NOT NULL, version integer NOT NULL DEFAULT 1, request_key text NOT NULL UNIQUE,
 last_operation text NOT NULL, CHECK (owner_member_id<>counterpart_member_id)
);
CREATE INDEX service_member_time ON service_records(owner_member_id,appointment_at DESC,id DESC);
CREATE INDEX service_member_status ON service_records(owner_member_id,status,appointment_at DESC,id DESC);
CREATE TABLE service_record_revisions (id text PRIMARY KEY, record_id text NOT NULL REFERENCES service_records(id), actor_id text NOT NULL REFERENCES users(id), digest text NOT NULL, before_data text, after_data text NOT NULL, reason text NOT NULL, created_at bigint NOT NULL);
CREATE INDEX service_revisions_record ON service_record_revisions(record_id,created_at);
CREATE TABLE photo_sources (media_id text PRIMARY KEY REFERENCES media(id), member_id text NOT NULL REFERENCES members(id), object_key text NOT NULL UNIQUE, digest text NOT NULL, content_type text NOT NULL, size bigint NOT NULL, state text NOT NULL CHECK (state IN ('pending','ready','deleting')), created_by text NOT NULL REFERENCES users(id), created_at bigint NOT NULL);
CREATE INDEX photo_sources_member ON photo_sources(member_id);
